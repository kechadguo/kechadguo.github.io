/* ---- 本地检索引擎 ---- */

// 检索停用词（提问常见虚词，不参与匹配）
const KNOWLEDGE_STOPWORDS = ['请问', '怎么', '如何', '为什么', '怎么办', '为什么', '一下', '宝宝', '孩子', '婴儿', '宝贝', '我们', '我家', '什么', '一个', '可以', '应该', '需要', '是不是', '有没有', '啥', '呢', '吗', '呀', '啊', '哦', '的', '了', '吗', '吧', '我', '你', '他', '她'];

// 从条目构建检索用关键词集：keys=title+tags（标签匹配），titleKeys=title（精确标题匹配，权重更高）
function _buildKnowledgeIndex() {
  const index = [];
  for (const topic of window.KNOWLEDGE_TREE) {
    for (const item of topic.items) {
      const keys = new Set([item.title]);
      for (const t of item.tags) keys.add(t);
      index.push({ topic, item, keys: [...keys], titleKeys: [item.title] });
    }
  }
  return index;
}

let _knowledgeCache = null;
function _getKnowledgeIndex() {
  if (!_knowledgeCache) _knowledgeCache = _buildKnowledgeIndex();
  return _knowledgeCache;
}

/* 本地检索：query → 匹配条目（相关度降序）
 * 评分：title 精确命中 +6，tag 命中 +3，content 含关键词 +1；命中个数越多分越高
 * 支持口语整句（如「宝宝不吃奶怎么办」）：自动扩展 2-4 字连续子串做正文模糊匹配
 */
window.searchKnowledge = function (query) {
  const q = String(query || '').trim();
  if (!q) return [];
  // 1) 标点分词 → 候选词（停用词过滤 + 去重）
  const words = q.split(/[，。！？、\s,.!?]+/).filter(Boolean);
  const candidates = [];
  for (const w of words) {
    if (KNOWLEDGE_STOPWORDS.includes(w) || w.length < 2) continue;
    if (!candidates.includes(w)) candidates.push(w);
  }
  // 2) 若整句不在停用词内，也作为整体候选（如「偏头」「5S」）
  const whole = q.replace(/[，。！？、\s,.!?]+/g, '');
  if (!KNOWLEDGE_STOPWORDS.includes(whole) && whole.length >= 2 && !candidates.includes(whole)) candidates.unshift(whole);

  // 3) 长候选（>=5 字，多为语音转出的口语整句）扩展 2-4 字连续子串；
  //    同时长句本身不参与下方 tag 匹配（避免与子串重复计分），仅靠 titleHit + 子串兜底
  const subCands = [];
  const shortCands = [];
  for (const c of candidates) {
    if (c.length >= 5) {
      for (let len = 4; len >= 2; len--) {
        for (let i = 0; i + len <= c.length; i++) {
          const sub = c.slice(i, i + len);
          if (subCands.includes(sub) || KNOWLEDGE_STOPWORDS.includes(sub)) continue;
          subCands.push(sub);
        }
      }
    } else {
      shortCands.push(c);
    }
  }

  // 4) 遍历索引打分
  const results = [];
  for (const entry of _getKnowledgeIndex()) {
    let score = 0;
    // title 精确命中（最高权重）
    const titleHit = entry.titleKeys.some(k => k === whole || (whole.length >= 2 && whole.includes(k)) || (k.length >= 2 && k.includes(whole)));
    if (titleHit) score += 6;
    // tag / title 关键词命中（仅短候选，避免长句误伤）
    for (const c of shortCands) {
      for (const k of entry.keys) {
        if (k.includes(c) || c.includes(k)) { score += 3; break; }
      }
      // 正文命中
      if (entry.item.content.includes(c)) score += 1;
    }
    // 子串模糊匹配：子串精确等于条目的 tag/title 词 → 加权（概念命中）；正文含子串 → +1
    for (const s of subCands) {
      const tagHit = entry.keys.some(k => k === s);
      if (tagHit) score += 3;
      if (entry.item.content.includes(s)) score += 1;
    }
    if (score > 0) results.push({ topic: entry.topic, item: entry.item, score });
  }
  results.sort((a, b) => b.score - a.score);
  return results;
};

/* 分类浏览：返回主题列表（含条目数）
 * 传 monthAge 时 count 为「适合该月龄」的条目数（向后兼容：不传则全量）
 */
window.getKnowledgeCategories = function (monthAge) {
  return window.KNOWLEDGE_TREE.map(t => ({
    key: t.key, name: t.name, icon: t.icon, desc: t.desc,
    count: monthAge == null ? t.items.length : t.items.filter(i => _inMonthRange(i, monthAge)).length
  }));
};

/* 判断条目是否适合某月龄（无 minMonth/maxMonth 视为全月龄适用） */
function _inMonthRange(item, monthAge) {
  const min = (item.minMonth == null ? 0 : item.minMonth);
  const max = (item.maxMonth == null ? 999 : item.maxMonth);
  return monthAge >= min && monthAge <= max;
}

/* 获取主题下适合某月龄的条目（monthAge 为 null 时返回全部） */
window.getKnowledgeItemsByAge = function (topicKey, monthAge) {
  const topic = window.KNOWLEDGE_TREE.find(t => t.key === topicKey);
  if (!topic) return [];
  if (monthAge == null) return topic.items;
  return topic.items.filter(i => _inMonthRange(i, monthAge));
};

/* 取单条知识（按主题 key + 标题） */
window.getKnowledgeItem = function (topicKey, title) {
  const topic = window.KNOWLEDGE_TREE.find(t => t.key === topicKey);
  if (!topic) return null;
  return topic.items.find(i => i.title === title) || null;
};

window.getKnowledgeTopic = function (key) {
  return window.KNOWLEDGE_TREE.find(t => t.key === key) || null;
};
