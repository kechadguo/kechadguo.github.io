/**
 * 从标准化数据中计算指定百分位的值
 * 使用 P50 ± (high-low)/3.92 * z 近似（±2SD 覆盖约 3.92 SD）
 */
function computePercentileValue(month, median, low2SD, high2SD, pKey) {
  var z = PERCENTILE_Z[pKey];
  var sd = (high2SD - low2SD) / 3.92;  // 估算每 SD 的跨度
  return +(median + z * sd).toFixed(1);
}

/**
 * 获取某月龄的百分位曲线数据点
 * @returns {Array<{month: number, value: number}>}
 */
function getPercentileCurve(gender, type, pKey) {
  var track = GROWTH_STANDARD.sourceTrack || 'who';
  var source = track === 'china2009' && window.GROWTH_STANDARD_CHINA_2009 ? window.GROWTH_STANDARD_CHINA_2009 : GROWTH_STANDARD;
  var ref = source[normalizeGender(gender)] && source[normalizeGender(gender)][type];
  if (!ref) return [];
  return ref.map(function(row) {
    var month = row[0], median = row[1], low = row[2], high = row[3];
    return { month: month, value: (pKey === 'P3' ? low : pKey === 'P50' ? median : pKey === 'P97' ? high : computePercentileValue(month, median, low, high, pKey)) };
  });
}

/**
 * 计算单次测量值所处的百分位
 * @returns {{ percentile: number, band: string, zScore: number, median: number }}
 */
window.assessPercentile = function(monthAge, gender, value, type) {
  var track = GROWTH_STANDARD.sourceTrack || 'who';
  var source = track === 'china2009' && window.GROWTH_STANDARD_CHINA_2009 ? window.GROWTH_STANDARD_CHINA_2009 : GROWTH_STANDARD;
  var ref = source[normalizeGender(gender)] && source[normalizeGender(gender)][type];
  if (!ref) return null;
  // 找最近月龄
  var nearest = ref[0];
  for (var i = 0; i < ref.length; i++) {
    if (ref[i][0] <= monthAge) nearest = ref[i];
  }
  var median = nearest[1], low = nearest[2], high = nearest[3];
  var sd = (high - low) / 3.92;
  var zScore = sd > 0 ? (value - median) / sd : 0;

  // 通过正态 CDF 近似计算百分位
  var percentile = Math.round(normalCDF(zScore) * 100);

  var band;
  if (percentile >= 97) band = '>P97';
  else if (percentile >= 90) band = 'P90-P97';
  else if (percentile >= 75) band = 'P75-P90';
  else if (percentile >= 25) band = 'P25-P75';
  else if (percentile >= 10) band = 'P10-P25';
  else if (percentile >= 3) band = 'P3-P10';
  else band = '<P3';

  return { percentile: percentile, band: band, zScore: +zScore.toFixed(2), median: median };
};

/** 标准正态 CDF 近似（Abramowitz and Stegun 公式） */
function normalCDF(x) {
  var t = 1 / (1 + 0.2316419 * Math.abs(x));
  var d = 0.3989423 * Math.exp(-x * x / 2);
  var p = d * t * (0.3193815 + t * (-0.3565638 + t * (1.781478 + t * (-1.821256 + t * 1.330274))));
  return x > 0 ? 1 - p : p;
}

