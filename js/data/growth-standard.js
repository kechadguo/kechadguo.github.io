window.evaluateGrowth = function(monthAge, gender, value, type) {
  var track = GROWTH_STANDARD.sourceTrack || 'who';
  var source = track === 'china2009' && window.GROWTH_STANDARD_CHINA_2009 ? window.GROWTH_STANDARD_CHINA_2009 : GROWTH_STANDARD;
  var data = source[normalizeGender(gender)] && source[normalizeGender(gender)][type];
  if (!data || !data.length) return { status: 'unavailable', label: '暂无该数据源', percentile: null, band: null };
  var nearest = data[0];
  for (var i = 0; i < data.length; i++) {
    if (data[i][0] <= monthAge) nearest = data[i];
  }
  var median = nearest[1], minSD = nearest[2], maxSD = nearest[3];

  // 同时计算百分位
  var pResult = window.assessPercentile(monthAge, gender, value, type);

  var result = {
    median: median,
    range: minSD + ' ~ ' + maxSD,
    percentile: pResult ? pResult.percentile : null,
    band: pResult ? pResult.band : null,
    zScore: pResult ? pResult.zScore : null
  };

  if (value < minSD) {
    result.status = 'low';
    result.label = '偏低';
    result.color = '#FF4D4F';
  } else if (value > maxSD) {
    result.status = 'high';
    result.label = '偏高';
    result.color = '#FAAD14';
  } else {
    result.status = 'normal';
    result.label = '正常';
    result.color = '#52C41A';
  }
  return result;
};

window.validateGrowthStandard = function() {
  var source = window.GROWTH_STANDARD;
  var result = { sourceTrack: source.sourceTrack || 'who', coverage: source.coverageMonths || [0, 0], datasets: {} };
  ['boy', 'girl'].forEach(function(gender) {
    result.datasets[gender] = {};
    ['weight', 'height', 'headCircumference'].forEach(function(type) {
      var rows = source[gender] && source[gender][type] || [];
      var monotonic = rows.every(function(row, i) { return i === 0 || row[0] > rows[i - 1][0]; });
      var bounds = rows.every(function(row) { return row.length === 4 && row[2] < row[1] && row[1] < row[3]; });
      result.datasets[gender][type] = { count: rows.length, minMonth: rows[0] ? rows[0][0] : null, maxMonth: rows.length ? rows[rows.length - 1][0] : null, monotonic: monotonic, orderedBounds: bounds };
    });
  });
  return result;
};
