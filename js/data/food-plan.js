/**
 * 获取指定月龄的辅食计划（6-12 月龄；超出范围返回 null）
 */
window.getFoodPlan = function (monthAge) {
  const m = Math.round(monthAge);
  return window.FOOD_PLAN.find(function (g) { return g.month === m; }) || null;
};

/**
 * 获取宝宝当月某一天的辅食安排（dayOfMonth: 1-30）
 * 返回 { meal, snack } 或 null
 */
window.getTodayFood = function (monthAge, dayOfMonth) {
  const g = window.getFoodPlan(monthAge);
  if (!g || !g.days) return null;
  for (const d of g.days) {
    if (d.day === dayOfMonth) return d;
  }
  return null;
};

/**
 * 今日辅食已添加记录（localStorage）
 * key: food-check-YYYYMMDD → JSON 数组 ['米粉5g+60ml水+菠菜泥', '香蕉泥', ...]
 * 与运动打卡同模式；本地缓存，后续版本可升级云端
 */
window.FoodCheck = {
  _key(today) {
    const d = today || new Date();
    const p = (n) => (n < 10 ? '0' + n : '' + n);
    return 'food-check-' + d.getFullYear() + p(d.getMonth() + 1) + p(d.getDate());
  },
  get(today) {
    try { return JSON.parse(localStorage.getItem(this._key(today)) || '[]'); }
    catch (e) { return []; }
  },
  add(name, today) {
    const list = this.get(today);
    if (name && !list.includes(name)) list.push(name);
    localStorage.setItem(this._key(today), JSON.stringify(list));
  },
  remove(name, today) {
    const list = this.get(today).filter(x => x !== name);
    localStorage.setItem(this._key(today), JSON.stringify(list));
  },
  has(name, today) {
    return this.get(today).includes(name);
  },
  count(today) {
    return this.get(today).length;
  },
  /** 近 N 天记录（含日期），用于历史浏览 */
  history(days) {
    const out = [];
    const today = new Date();
    for (let i = 0; i < days; i++) {
      const d = new Date(today.getFullYear(), today.getMonth(), today.getDate() - i);
      const list = this.get(d);
      if (list.length) out.push({ date: d, list });
    }
    return out;
  }
};
